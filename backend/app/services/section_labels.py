"""Двуязычные подписи разделов статьи.

Имя раздела — технический контракт: его backend держит в плане, в ключе
генерации и в ссылках API, поэтому `Introduction` там менять нельзя.
Пользователь же читает по-русски и одновременно сверяется с планом журнала,
который на английском. Поэтому в тексте, который видит человек, раздел
называется «Введение (Introduction)».

Живёт отдельно от `generation.py`, потому что используется в трёх местах,
которые не должны зависеть друг от друга: подсказки разбора черновика,
текст ошибки API и заголовки выгрузки.
"""

from __future__ import annotations

# Техническое имя раздела → русский термин. Ключи в том виде, в каком их
# отдаёт `DEFAULT_SECTIONS`; сравнение регистронезависимое.
SECTION_TITLES: dict[str, str] = {
    "introduction": "Введение",
    "methods": "Методы исследования",
    "materials and methods": "Методы исследования",
    "results": "Результаты",
    "discussion": "Обсуждение",
    "conclusions": "Заключение",
    "conclusion": "Заключение",
}


def section_title(name: str) -> str:
    """«Introduction» -> «Введение (Introduction)».

    Раздел, которого нет в справочнике, возвращается как есть: собственное
    имя раздела полезнее пустоты, иначе в подсказке будет «Раздел «»
    не написан».
    """
    clean = (name or "").strip()
    if not clean:
        return clean
    title = SECTION_TITLES.get(clean.lower())
    return f"{title} ({clean})" if title else clean


__all__ = ["SECTION_TITLES", "section_title"]