"""Болтовня и вопросы о помощнике — быстрый путь без поиска по базе.

Здравствуйте, спасибо и подобное: запрос, по которому в базе искать нечего.
Гонять такие фразы в RAG дорого и бессмысленно: замер 2026-10-18 показал,
что «привет» стоит ~43 с (12 параллельных сводок плюс автоматический повтор
поиска без сводок), и примерно половина этого уходит впустую.

Хуже того, поиск по базе на болтовню возвращает мусор, и модель пишет на него
ответ С ССЫЛКАМИ. Это прямое нарушение GROUNDING RULES из промпта paperqa
(«нет подходящего контекста — ответ отказывается отвечать»), причём
заметное пользователю: на «привет» он получал рассуждение о «взгляде с
информационной точки зрения» со ссылкой на чужой документ. Для приветствия
отказ неуместен, поэтому здесь нужен разговорный ответ.

Список закрытый, проверка строгая: срабатывает ТОЛКО когда запрос целиком
совпал с одной из фраз. «привет» — болтовня, «привет, что такое CTD?» —
нормальный вопрос. Никаких эвристик по длине или знакам препинания: они дали
бы ложные срабатывания на коротких, но содержательных запросах («GF/F?»,
«хлорофилл»), а цена ошибки — потерянный ответ по теме.
"""

from __future__ import annotations

import logging
import re

log = logging.getLogger("boasi.services.rag")

# Имя помощника. Спрашивают пользователи, и ответ должен быть один и тот же:
# модель на маленьких моделях в разных сессии называет себя по-разному, а
# пользователь это видит. Значение одно — и в промпте, и в запасном ответе.
ASSISTANT_NAME = "Бо"

# Ответ, если модель на вопрос о помощнике вернула отказ. Проверка по началу
# строки: формулировок отказа много, и смысл один — «источников нет».
_REFUSAL_MARKERS = (
    "не могу ответить",
    "недостаточно информации",
    "нет информации",
    "невозможно ответить",
    "не нашл",
    "не нашлось",
    "нет сведений",
    "сведений нет",
)

# Косвенный признак отказа: первая фраза говорит об источниках И о том, что
# их не хватило. Перечисление форм («источников нет», «нет источников»,
# «источники не содержат») не работает: между словами вставляются «по этому
# вопросу», «в базе», «среди них» — вариантов бесконечно много.
_REFUSAL_SOURCE_WORD = "источник"
_REFUSAL_NEGATION = ("нет", "не содерж", "не даёт", "не найден", "не хватает")

_IDENTITY_FALLBACK = (
    f"Меня зовут {ASSISTANT_NAME}. Я помощник исследователя в этой системе: "
    "ищу по загруженной базе знаний и отвечаю со ссылками на источники, "
    "работаю с сессиями и проектами статей."
)

TRIVIAL_QUERIES = frozenset({
    "привет", "приветик", "приветики", "здравствуй", "здравствуйте",
    "добрый день", "доброе утро", "добрый вечер", "доброго дня",
    "доброй ночи", "хай", "спасибо", "спасибочки", "благодарю",
    "пожалуйста", "простите", "извините", "пока", "до свидания",
    "прощай", "да", "нет", "ага", "угу", "ок", "окей", "хорошо",
    "ясно", "понятно", "принято", "тест", "тестик", "йо", "хеллоу",
    "hi", "hello", "hey", "thanks", "thank you", "ok", "okay", "yes", "no",
})

# Вопросы о самом помощнике: кто я, как меня зовут, что я умею. Отдельный
# словарь, а не дополнение `TRIVIAL_QUERIES`: на них нужен ДРУГОЙ ответ —
# не «спросите про базу», а представление и объяснение, что я умее.
# Список закрытый по той же причине: «ты бот?» — вопрос обо мне, а «что
# такое биобот?» — обычный вопрос по теме, и он должен уйти в базе.
IDENTITY_QUERIES = frozenset({
    "ты кто", "кто ты", "кто ты такой", "кто ты такая", "кто вы",
    "как тебя зовут", "как вас зовут", "как тебя звать", "твоё имя",
    "твое имя", "представься", "расскажи о себе", "ты бот", "ты робот",
    "ты машина", "ты человек", "ты человек или машина", "ты настоящий",
    "ты искусственный интеллект", "ты ии", "что ты умеешь", "что ты можешь",
    "чем ты можешь помочь", "чем ты помогаешь", "зачем ты нужен",
    "зачем ты нужна", "что ты делаешь", "как ты работаешь",
    "who are you", "whats your name", "what are you", "what can you do",
    "your name", "introduce yourself",
})


def is_trivial_query(query: str) -> bool:
    """Болтовня ли это — запрос, для которого поиск по базе не нужен.

    Проверка намеренно примитивная: сравнение строки целиком по закрытому
    списку. Словарь состоит из слов, поэтому термин с такой же формой
    («нет») в него не попадает.
    """
    normalized = re.sub(r"[^\w\s]", " ", (query or "").lower(), flags=re.UNICODE)
    normalized = " ".join(normalized.split())
    if not normalized or len(normalized.split()) > 3:
        return False
    return normalized in TRIVIAL_QUERIES


def is_identity_query(query: str) -> bool:
    """Спрашивает ли пользователь о самом помощнике.

    Та же строгая проверка, что в `is_trivial_query`: полное совпадение с
    фразой из закрытого списка. Эвристика «вопрос содержит слово "ты"» поймала
    бы «ты знаешь, что такое биомасса?» — а это вопрос по теме, и цена ошибки
    здесь та же, что у болтовни: потерянный ответ по существу.
    """
    normalized = re.sub(r"[^\w\s]", " ", (query or "").lower(), flags=re.UNICODE)
    normalized = " ".join(normalized.split())
    if not normalized or len(normalized.split()) > 4:
        return False
    return normalized in IDENTITY_QUERIES


def is_refusal(text: str) -> bool:
    """Отказала ли модель — по началу ответа, а не по вхождению где угодно.

    Смотрится только ПЕРВАЯ ФРАЗА: иначе нормальный ответ, который честно
    упоминает ограничения («Меня зовут Бо. В источниках нет данных по этому
    вопросу, но…»), принимается за отказ и выбрасывается вместе с представлением.
    """
    head = (text or "").strip().lower()
    first = re.split(r"[.\n!]", head, maxsplit=1)[0]
    if any(marker in first for marker in _REFUSAL_MARKERS):
        return True
    return (_REFUSAL_SOURCE_WORD in first
            and any(word in first for word in _REFUSAL_NEGATION))


def trivial_prompt(query: str, kind: str = "greeting") -> str:
    """Промпт для болтовни и для вопроса о помощнике.

    Для болтовни — коротко, по-русски, без ссылок и выдумки. Для вопроса
    обо мне — с тем же требованием, но модель должна представиться и
    сказать, что умеет; обещать то, чего система не делает (поиск в
    интернете, доступ к приборам), запрещено явно.
    """
    if kind == "identity":
        return (
            "Пользователь спросил поисковую систему по научной литературе "
            f"ровно это: {query!r}. Вопрос обо мне, а не о теме — искать "
            "по базе нечего, источников он не ждёт."
            "\n\n"
            "Ответи по-усски от первого лица, дружелюбно и КРАТКО "
            "(2-4 предложения). Обязательно:\n"
            f"1. начни сразу с представления, без приветствия: тебя зовут "
            f"{ASSISTANT_NAME};\n"
            "2. скажи, что ты помощник исследователя в этой системе и "
            "отвечаешь по загруженной базе знаний — со ссылками на "
            "источники;\n"
            "3. в двух словах назови, что умеешь (искать по базе, "
            "отвечать на вопросы по документам, работать с сессиями и "
            "проектами статей).\n"
            "Жёсткие запреты: не выдумывай и не упоминай интернет, "
            "актуальные данные, свежие новости, приборы и чужие документы — "
            "у тебя нет ничего из этого; не упоминай источники и не ставь "
            "сносок. Только имя — Бо."
            "\n\nПример хорошего ответа:\n"
            f"«Меня зовут {ASSISTANT_NAME}. Я помощник исследователя в этой "
            "системе: отвечаю на вопросы по загруженной базе знаний и "
            "показываю, на какие источники опираюсь. Помогаю искать по "
            "документам, вести сессию и готовить статью к выгрузке.»"
        )
    return (
        "Пользователь написал в поисковой системе по научной литературе "
        f"ровно это: {query!r}. Это не вопрос по теме, а приветствие, "
        "благодарность или прощальная реплика."
        "\n\n"
        + "Ответи по-усски, дружелюбно и ОЧЕНЬ кратко (1-2 предложения). "
        "Ничего не цитируй и не выдумывай: предложи спросить про базу "
        "знаний или уточнить тему."
    )


